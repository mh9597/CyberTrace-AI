from typing import List
from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from backend.app.db.database import get_db
from backend.app.api.deps import get_current_user
from backend.app.models.user import User
from backend.app.models.prediction import Prediction
from backend.app.schemas.prediction import (
    PredictionResponse,
    HotspotCluster,
    CandidateLeadZone,
)
from backend.app.services.complaint_service import get_complaint_by_id
from backend.app.services.prediction_service import (
    run_prediction_pipeline,
    get_all_hotspots,
    get_all_candidate_zones,
)
from backend.app.services.audit_service import log_audit_event

router = APIRouter(tags=["AI Prediction Engine & Geospatial Map"])


@router.post("/complaints/{complaint_id}/predict", response_model=PredictionResponse)
def generate_prediction(
    complaint_id: str,
    force_recalculate: bool = Query(False),
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    complaint = get_complaint_by_id(db, complaint_id)
    if not complaint:
        raise HTTPException(status_code=404, detail="Complaint record not found")

    prediction = run_prediction_pipeline(db, complaint.id, force_recalculate=force_recalculate)
    log_audit_event(
        db=db,
        action="PREDICTION_EXECUTED",
        target_record=complaint.complaint_id,
        user_id=current_user.id,
        user_email=current_user.email,
        details=f"Generated forecast candidate: {prediction.candidate_zone} (Risk: {prediction.risk_estimate})",
    )
    return PredictionResponse.model_validate(prediction)


@router.get("/complaints/{complaint_id}/predictions", response_model=List[PredictionResponse])
def get_case_predictions(
    complaint_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    complaint = get_complaint_by_id(db, complaint_id)
    if not complaint:
        raise HTTPException(status_code=404, detail="Complaint record not found")

    predictions = (
        db.query(Prediction)
        .filter(Prediction.complaint_id == complaint.id)
        .order_by(Prediction.created_at.desc())
        .all()
    )
    return [PredictionResponse.model_validate(p) for p in predictions]


@router.get("/map/hotspots", response_model=List[HotspotCluster])
def get_hotspot_clusters(current_user: User = Depends(get_current_user)):
    """Returns historical withdrawal hotspot clusters discovered via DBSCAN."""
    return get_all_hotspots()


@router.get("/map/candidate-zones", response_model=List[CandidateLeadZone])
def get_candidate_forecast_zones(
    db: Session = Depends(get_db), current_user: User = Depends(get_current_user)
):
    """Returns active forecast candidate zones generated by the ML engine."""
    return get_all_candidate_zones(db)
